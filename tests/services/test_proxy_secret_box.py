import os
import stat

from cryptography.fernet import Fernet

from broxy4g.services.proxy_secret_box import KEY_ENV_VAR, ProxySecretBox


def _key() -> str:
    return Fernet.generate_key().decode()


def test_roundtrip_with_env_key(monkeypatch):
    monkeypatch.setenv(KEY_ENV_VAR, _key())
    box = ProxySecretBox()
    token = box.encrypt("mot-de-passe-32-caracteres-abcdefghijklmnopqrstuvwxyz")
    assert token is not None
    assert box.decrypt(token) == "mot-de-passe-32-caracteres-abcdefghijklmnopqrstuvwxyz"


def test_encrypt_decrypt_with_explicit_key():
    box = ProxySecretBox(key=_key())
    token = box.encrypt("secret")
    assert box.decrypt(token) == "secret"


def test_autogenerated_key_stable_across_instantiations(tmp_path):
    path = tmp_path / "proxy.key"
    first = ProxySecretBox(key_path=path)
    token = first.encrypt("abc")
    # Une seconde instanciation sur le même chemin relit la même clé.
    second = ProxySecretBox(key_path=path)
    assert second.decrypt(token) == "abc"


def test_autogenerated_key_file_is_0600(tmp_path):
    path = tmp_path / "proxy.key"
    ProxySecretBox(key_path=path)
    mode = stat.S_IMODE(os.stat(path).st_mode)
    assert mode == 0o600


def test_decrypt_missing_token_returns_none():
    box = ProxySecretBox(key=_key())
    assert box.decrypt(None) is None
    assert box.decrypt("") is None


def test_decrypt_corrupt_token_returns_none(caplog):
    box = ProxySecretBox(key=_key())
    assert box.decrypt("not-a-valid-fernet-token") is None


def test_decrypt_with_rotated_key_returns_none(caplog):
    a = ProxySecretBox(key=_key())
    token = a.encrypt("secret")
    # Clé rotée : la valeur chiffrée n'est plus déchiffrable.
    b = ProxySecretBox(key=_key())
    assert b.decrypt(token) is None


def test_no_key_no_path_is_fail_closed_and_silent(monkeypatch, caplog):
    # Ni clé env ni chemin : coffre indisponible, jamais de crash, pas de
    # secret dans les logs.
    monkeypatch.delenv(KEY_ENV_VAR, raising=False)
    box = ProxySecretBox()
    assert box.available is False
    assert box.encrypt("secret") is None
    assert box.decrypt("whatever") is None


def test_invalid_env_key_is_fail_closed(monkeypatch):
    monkeypatch.setenv(KEY_ENV_VAR, "pas-une-cle-fernet-valide")
    box = ProxySecretBox()
    assert box.available is False
    assert box.encrypt("secret") is None
    assert box.decrypt("whatever") is None


def test_logs_never_contain_secret(caplog):
    box = ProxySecretBox(key=_key())
    secret = "secret-super-secreet-42"
    box.encrypt(secret)
    box.decrypt("corrupted-token-value")
    assert secret not in caplog.text
